using System.Collections.Generic;
using System.Linq;

namespace SpectraEngine.Entities.Generator.ScriptApi;

// Writes the generated half of one class that declares a part of the
// script API: its binding, and what it declares as data.
internal static class ScriptContainerEmitter
{
    public static string HintName(ScriptContainerModel model) =>
        ScriptNames.Flat(model.FullTypeName) + ".ScriptApi.g.cs";

    public static string Emit(ScriptContainerModel model)
    {
        var w = new SourceWriter();
        w.Line("// <auto-generated/>");
        w.Line("#nullable enable");
        w.Line();

        if (model.Namespace.Length > 0)
            w.Open($"namespace {model.Namespace}");

        for (int i = 0; i < model.ContainingTypes.Count; i++)
            w.Open(model.ContainingTypes[i]);

        w.Open(OwnDeclaration(model));

        if (model.Kind is ScriptContainerKind.Class or ScriptContainerKind.Value)
            ScriptClassEmitter.Emit(w, model);
        else
            ScriptLibraryEmitter.Emit(w, model);

        ScriptDescriptionEmitter.Emit(w, model);
        w.Close();

        for (int i = 0; i < model.ContainingTypes.Count; i++)
            w.Close();

        if (model.Namespace.Length > 0)
            w.Close();

        return w.ToString();
    }

    // What the catalogue needs of the container.
    public static ScriptCatalogEntry CatalogEntryOf(ScriptContainerModel model)
    {
        bool holdsObjects = model.Kind is ScriptContainerKind.Class or ScriptContainerKind.Value;
        string[] names = holdsObjects && model.Self is not null
            ? model.Properties.Select(property => property.LuauName)
                .Concat(model.Functions.Select(function => function.LuauName))
                .ToArray()
            : new string[0];

        return new ScriptCatalogEntry(
            model.Kind,
            model.FullTypeName,
            model.LuauName,
            model.Extends,
            SelfType: holdsObjects ? model.Self?.ClrType ?? "" : "",
            new EquatableArray<string>(names),
            HasMethods: holdsObjects && model.Self is not null && model.Functions.Count > 0,
            model.IsStatic,
            new EquatableArray<string>(ReopensOf(model)));
    }

    private static string OwnDeclaration(ScriptContainerModel model) => $"partial class {model.TypeName}";

    private static string[] ReopensOf(ScriptContainerModel model)
    {
        var reopens = new List<string>();
        if (model.Namespace.Length > 0)
            reopens.Add($"namespace {model.Namespace}");

        reopens.AddRange(model.ContainingTypes);
        reopens.Add(OwnDeclaration(model));
        return reopens.ToArray();
    }

    public static ScriptContainerPlace PlaceOf(ScriptContainerModel model) =>
        new(CatalogEntryOf(model), model.Location);
}
