using System;
using System.Collections.Generic;
using System.Linq;
using System.Text;

namespace SpectraEngine.Entities.Generator.ScriptApi;

// Writes the one file that knows every container: the atom of each member
// name, the id of each class, the whole description, and the method tables.
// Names and classes are numbered in the order of their names, so the
// numbers do not depend on the order of the files.
internal static class ScriptCatalogEmitter
{
    public const string HintName = "ScriptApiCatalog.g.cs";

    private static readonly string[] Accesses = { "Read", "Write", "Invoke" };

    // Takes every container. Of two under one name it lists the first.
    public static string Emit(IReadOnlyList<ScriptCatalogEntry> entries)
    {
        ScriptCatalogEntry[] ordered = ScriptCatalogEntry.Listed(entries)
            .OrderBy(entry => entry.LuauName, StringComparer.Ordinal)
            .ThenBy(entry => entry.FullTypeName, StringComparer.Ordinal)
            .ToArray();
        ScriptCatalogEntry[] classes = ordered
            .Where(entry => entry.Kind is ScriptContainerKind.Class or ScriptContainerKind.Value)
            .ToArray();
        string[] atoms = classes
            .SelectMany(entry => entry.MemberNames)
            .Distinct(StringComparer.Ordinal)
            .OrderBy(name => name, StringComparer.Ordinal)
            .ToArray();

        var w = new SourceWriter();
        w.Line("// <auto-generated/>");
        w.Line("#nullable enable");
        w.Line();

        // A member of a script class may be called Equals.
        w.Line("#pragma warning disable CS0108");
        w.Line();
        w.Open($"namespace {ScriptNames.RuntimeNamespace}");
        EmitNumbers(w, "ScriptAtoms", "The number of each member name of the script API, which Luau hands over in place of the name.", atoms);
        EmitNumbers(w, "ScriptClassIds", "The number of each class and value type of the script API.", classes.Select(entry => entry.LuauName).ToArray());
        EmitCatalog(w, ordered, classes, atoms);
        EmitBases(w, entries, ordered);
        w.Close();
        EmitHandOns(w, ordered);
        return w.ToString();
    }

    // A class that declares no member has no switches in its own file, and
    // only the catalogue knows the type of its object. So its switches are
    // written here, and each hands the name to the class it extends. A
    // class picked by what an object is can then always be asked.
    private static void EmitHandOns(SourceWriter w, IReadOnlyList<ScriptCatalogEntry> listed)
    {
        foreach (ScriptCatalogEntry entry in listed)
        {
            if (ScriptExtends.HandsOnTo(entry, listed) is not { } above)
                continue;

            string self = ScriptExtends.ObjectTypeOf(entry, listed);
            w.Line();
            for (int i = 0; i < entry.Reopens.Count; i++)
                w.Open(entry.Reopens[i]);

            w.Line($"// {entry.LuauName} declares no member itself, so each of these hands the atom to {above.LuauName}.");
            foreach (string access in Accesses)
            {
                w.Line(
                    $"internal static int Script{access}({ScriptNames.Context} context, {ScriptNames.Stack} stack, " +
                    $"{self} self, int atom) =>");
                w.Indent().Line($"{above.FullTypeName}.Script{access}(context, stack, self, atom);").Outdent();
                w.Line();
            }

            for (int i = 0; i < entry.Reopens.Count; i++)
                w.Close();
        }
    }

    // What the switch of a class that extends another calls for a name it
    // does not declare. A class the binding cannot follow hands on to nothing.
    private static void EmitBases(
        SourceWriter w, IReadOnlyList<ScriptCatalogEntry> entries, IReadOnlyList<ScriptCatalogEntry> listed)
    {
        ScriptCatalogEntry[] extending = entries
            .Where(entry => entry.Extends.Length > 0 && entry.SelfType.Length > 0)
            .OrderBy(entry => entry.FullTypeName, StringComparer.Ordinal)
            .ToArray();
        if (extending.Length == 0)
            return;

        w.Line();
        w.Line("/// <summary>Hands a member a class does not declare itself to the class it extends.</summary>");
        w.Open("internal static class ScriptBases");
        foreach (ScriptCatalogEntry entry in extending)
        {
            ScriptCatalogEntry? above = ScriptExtends.BaseOf(entry, listed, out _);
            foreach (string access in Accesses)
            {
                string answer = above is null
                    ? $"{ScriptNames.Member}.None"
                    : $"{above.FullTypeName}.Script{access}(context, stack, self, atom)";

                w.Line(
                    $"internal static int {ScriptNames.BaseCall(access, entry.FullTypeName)}({ScriptNames.Context} context, " +
                    $"{ScriptNames.Stack} stack, {entry.SelfType} self, int atom) =>");
                w.Indent().Line($"{answer};").Outdent();
            }
        }

        w.Close();
    }

    private static void EmitNumbers(SourceWriter w, string type, string summary, string[] names)
    {
        w.Line($"/// <summary>{summary}</summary>");
        w.Open($"internal static class {type}");
        for (int i = 0; i < names.Length; i++)
            w.Line($"public const int {ScriptNames.Identifier(names[i])} = {i};");

        w.Close();
        w.Line();
    }

    private static void EmitCatalog(
        SourceWriter w, ScriptCatalogEntry[] ordered, ScriptCatalogEntry[] classes, string[] atoms)
    {
        w.Line("/// <summary>Everything the script API declares, gathered from the classes that declare it.</summary>");
        w.Open("internal static class ScriptApiCatalog");

        w.Line("/// <summary>How many member names have an atom.</summary>");
        w.Line($"public const int AtomCount = {atoms.Length};");
        w.Line();
        w.Line("/// <summary>The member names in the order of their atoms, each ended by a zero.</summary>");
        w.Line($"public static global::System.ReadOnlySpan<byte> AtomNames => {ScriptNames.Literal(JoinWithZeros(atoms))}u8;");
        w.Line();

        w.Line("/// <summary>The whole script API as data.</summary>");
        w.Line($"public static {ScriptNames.Api}.ScriptApiDescription Description {{ get; }} = new()");
        w.Line("{");
        w.Indent();
        EmitList(w, "Classes", classes.Select(entry => $"{entry.FullTypeName}.ScriptDescription"));
        EmitList(w, "Libraries", Of(ordered, ScriptContainerKind.Library).Select(entry => $"{entry.FullTypeName}.ScriptDescription"));
        EmitList(w, "Globals", Of(ordered, ScriptContainerKind.Globals).Select(entry => $".. {entry.FullTypeName}.ScriptGlobalValues"));
        EmitList(w, "Functions", Of(ordered, ScriptContainerKind.Globals).Select(entry => $".. {entry.FullTypeName}.ScriptGlobalFunctions"));
        w.Outdent();
        w.Line("};");
        w.Line();

        w.Line("/// <summary>The method table of each class, by its id. Null for a class with no methods.</summary>");
        w.Line($"public static {ScriptNames.MethodTable}?[] BuildMethods({ScriptNames.Context} context) =>");
        w.Line("[");
        w.Indent();
        foreach (ScriptCatalogEntry entry in classes)
            w.Line(entry.HasMethods ? $"{entry.FullTypeName}.ScriptMethods(context)," : "null,");

        w.Outdent();
        w.Line("];");
        w.Close();
    }

    private static IEnumerable<ScriptCatalogEntry> Of(ScriptCatalogEntry[] entries, ScriptContainerKind kind) =>
        entries.Where(entry => entry.Kind == kind);

    private static void EmitList(SourceWriter w, string member, IEnumerable<string> items)
    {
        w.Line($"{member} =");
        w.Line("[");
        w.Indent();
        foreach (string item in items)
            w.Line($"{item},");

        w.Outdent();
        w.Line("],");
    }

    private static string JoinWithZeros(string[] names)
    {
        var joined = new StringBuilder();
        foreach (string name in names)
            joined.Append(name).Append('\0');

        return joined.ToString();
    }
}
