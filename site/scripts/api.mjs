// Builds the C# API reference: runs DocFX over the engine projects, then turns
// its Markdown into Starlight pages under src/content/docs/reference/api.
import { execFileSync } from 'node:child_process';
import { mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const site = join(dirname(fileURLToPath(import.meta.url)), '..');
const raw = join(site, '.api');
const out = join(site, 'src', 'content', 'docs', 'reference', 'api');
const ROOT_NAMESPACE = 'SpectraEngine.';
const BASE = '/reference/api';

rmSync(raw, { recursive: true, force: true });
execFileSync('dotnet', ['docfx', 'metadata', 'docfx.json'], { cwd: join(site, 'api'), stdio: 'inherit' });

const slug = text => text.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');

// uid (the DocFX file name without .md) -> where the page lives on the site
const pages = new Map();
for (const file of readdirSync(raw).filter(name => name.endsWith('.md'))) {
	const uid = file.slice(0, -3);
	const text = readFileSync(join(raw, file), 'utf8');
	const heading = /^# <a id="[^"]*"><\/a> (\w+) (.+)$/m.exec(text);
	if (!heading) continue;

	const kind = heading[1];
	const name = heading[2].replace(/\\/g, '');
	const namespace = kind === 'Namespace' ? uid : (/^Namespace: \[([^\]]+)\]/m.exec(text)?.[1] ?? '');
	const folder = slug(namespace.startsWith(ROOT_NAMESPACE) ? namespace.slice(ROOT_NAMESPACE.length) : namespace);
	const leaf = kind === 'Namespace' ? 'index' : slug(uid.slice(namespace.length + 1));
	pages.set(uid, {
		text, kind, name, folder, leaf,
		route: kind === 'Namespace' ? `${BASE}/${folder}/` : `${BASE}/${folder}/${leaf}/`,
	});
}

const routeFor = (uid, anchor = '') => {
	const page = pages.get(uid);
	return page ? page.route + anchor : null;
};

function convert(page) {
	let body = page.text.replace(/^# <a id="[^"]*"><\/a> .+\r?\n/m, '');

	// Links between pages.
	// DocFX escapes the anchor ("\#Some\_Id").
	body = body.replace(/\]\(([A-Za-z0-9_.\-]+)\.md(\\?#[^)]*)?\)/g, (match, uid, anchor) => {
		const route = routeFor(uid, (anchor ?? '').replaceAll('\\', ''));
		return route ? `](${route})` : match;
	});

	// crefs inside summaries arrive as unresolved <xref> tags.
	body = body.replace(/<xref href="([^"]+)"[^>]*><\/xref>/g, (match, target) => {
		// DocFX file names spell a generic arity as -1 where the uid has `1.
		const uid = decodeURIComponent(target).replace(/\(.*$/, '').replace(/[`*]/g, '-').replace(/-$/, '');
		const label = uid.split('.').pop();
		for (let candidate = uid; candidate.includes('.'); candidate = candidate.slice(0, candidate.lastIndexOf('.'))) {
			const route = routeFor(candidate);
			if (route) return `[${label}](${route})`;
		}
		return `\`${label}\``;
	});

	// Members inherited from object are noise on every page.
	body = body.replace(/#### Inherited Members\r?\n\r?\n((?:\[object\.[^\n]*\r?\n)+)\r?\n?/g, '');

	const summary = body.split(/\r?\n\r?\n/).map(block => block.trim()).find(block =>
		block && !/^(Namespace:|Assembly:|```|#|<)/.test(block));
	const description = (summary ?? '').replace(/\[([^\]]+)\]\([^)]*\)/g, '$1').replace(/[`*]/g, '').replace(/\s+/g, ' ').trim();

	const front = [
		'---',
		`title: ${JSON.stringify(page.name)}`,
		description ? `description: ${JSON.stringify(description.slice(0, 200))}` : null,
		page.kind === 'Namespace' ? `sidebar:\n  label: Overview\n  order: 0` : null,
		'editUrl: false',
		'---',
		'',
	].filter(line => line !== null).join('\n');

	const lead = page.kind === 'Namespace' ? '' : `<span class="api-kind">${page.kind}</span>\n\n`;
	return front + lead + body.trimStart();
}

rmSync(out, { recursive: true, force: true });
for (const page of pages.values()) {
	const target = join(out, page.folder, `${page.leaf}.md`);
	mkdirSync(dirname(target), { recursive: true });
	writeFileSync(target, convert(page));
}

// Starlight labels an autogenerated group with its folder name, so the
// namespace groups are listed here with their real names.
const groups = [...pages.values()]
	.filter(page => page.kind === 'Namespace')
	.sort((a, b) => a.name.localeCompare(b.name))
	.map(page => ({
		label: page.name.startsWith(ROOT_NAMESPACE) ? page.name.slice(ROOT_NAMESPACE.length) : page.name,
		collapsed: true,
		items: [{ autogenerate: { directory: `reference/api/${page.folder}` } }],
	}));
writeFileSync(join(site, 'src', 'api-sidebar.json'), JSON.stringify(groups, null, '\t') + '\n');

console.log(`api: wrote ${pages.size} pages to ${out}`);
